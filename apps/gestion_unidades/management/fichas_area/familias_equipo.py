def _clave(nombre):
    sin_tildes = unicodedata.normalize('NFKD', nombre or '').encode('ascii', 'ignore').decode()
    return ' '.join(sin_tildes.lower().split())


_POR_CLAVE = {_clave(nombre): familia for nombre, familia in EQUIPOS.items()}


def familia_de(nombre):
    """La familia de un equipo por su nombre, sin distinguir mayúsculas ni tildes; vacío si no está."""
    return EQUIPOS.get(nombre) or _POR_CLAVE.get(_clave(nombre), '')
