def ampliar(definicion, ampliacion):
    """La definición de la planta con los equipos, insumos, productos y procesos de la ampliación.

    plantillas_derivadas fija de qué proceso parte un producto cuando el de su
    familia no le corresponde; sin_derivar lista lo que la planta no puede
    fabricar con sus equipos, con el motivo.
    """
    return {
        **definicion,
        **{
            clave: [*definicion.get(clave, []), *ampliacion.get(clave, [])]
            for clave in ('equipos', 'consumibles', 'productos', 'recetas', 'calidad')
        },
        'plantillas_derivadas': ampliacion.get('plantillas_derivadas', {}),
        'sin_derivar': ampliacion.get('sin_derivar', {}),
    }
