"""Procesos de referencia para las familias que no tenían ninguno (bloque 2 de la fase 1).

Cada planta ofrece al menos un proceso por familia de su taxonomía, con la misma
estructura que los existentes: etapas con su símbolo, equipo, espacio, tiempos,
rendimiento y controles; insumos por corrida base y salidas. Los PCC controlan
peligros de inocuidad (Codex CXC 1-1969); lo demás es un PC de calidad. Son
procesos de referencia: la planta los valida, y cada usuario puede copiarlos y
modificarlos para sus escenarios.

Los productos usan el código del catálogo de la taxonomía, así el proceso completa
la ficha del producto que ya existía en lugar de duplicarlo.
"""
from decimal import Decimal

from apps.plantas_piloto.operacion.management.plantas.taxonomia import PRODUCTOS_TAXONOMIA


def codigo_catalogo(prefijo, familia, nombre):
    """El código con el que el catálogo creó el producto de la taxonomía."""
    familias = list(PRODUCTOS_TAXONOMIA[prefijo])
    productos = [nombre_producto for nombre_producto, _ in PRODUCTOS_TAXONOMIA[prefijo][familia]]
    return f'{prefijo}-PRD-CAT-{familias.index(familia) + 1:02d}-{productos.index(nombre) + 1:02d}'


def equipo(codigo, nombre, categoria_codigo, categoria, icono, unidad, ubicacion, descripcion, caracteristicas,
           uso, instrucciones, accesorios=(), insumos=''):
    return {
        'codigo': codigo, 'nombre': nombre, 'categoria_codigo': categoria_codigo, 'categoria': categoria,
        'icono': icono, 'unidades': [unidad], 'descripcion': descripcion, 'caracteristicas_publicas': caracteristicas,
        'uso_publico': uso, 'instrucciones_publicas': instrucciones, 'software': 'No requiere programas de la planta',
        'accesorios': list(accesorios), 'requiere_insumos': bool(insumos), 'insumos': insumos or 'No requiere',
        'ubicacion': ubicacion,
    }


def insumo(codigo, nombre, clasificacion, familia, presentacion, por_presentacion, unidad, stock, minimo, precio,
           descripcion, ubicacion, proveedor='Proveedor calificado de la planta', equipos=()):
    return {
        'codigo': codigo, 'nombre': nombre, 'clasificacion': clasificacion, 'familia': familia, 'variante': '',
        'color': '', 'presentacion': presentacion, 'cantidad_por_presentacion': Decimal(por_presentacion),
        'unidad_medida': unidad, 'stock_total': Decimal(stock), 'minimo': Decimal(minimo),
        'precio_unitario': Decimal(precio), 'descripcion': descripcion, 'ubicacion': ubicacion,
        'proveedor': proveedor, 'plazo_dias': 7, 'equipos': list(equipos),
        'instrucciones_solicitud': 'Pide la cantidad por corrida base que declara el proceso.',
    }


def producto(codigo, familia, nombre, unidad, presentacion, precio, vida_util, frio, descripcion, tipo='terminado'):
    return {
        'codigo': codigo, 'familia': familia, 'nombre': nombre, 'tipo': tipo, 'unidad_medida': unidad,
        'presentacion': presentacion, 'precio_venta': precio, 'vida_util_dias': vida_util, 'requiere_frio': frio,
        'descripcion': descripcion,
    }


def residuo(codigo, familia, nombre, unidad, descripcion):
    return producto(codigo, familia, nombre, unidad, '', '0', 0, False, descripcion, tipo='residuo')


def etapa(nombre, tipo, equipo_codigo, espacio, duracion, personas=1, espera=0, rendimiento='100', distancia='0',
          pcc=None, pc=None, instrucciones=''):
    """pcc/pc: (parámetro, límite). PCC = inocuidad; PC = calidad o proceso."""
    datos = {'nombre': nombre, 'tipo': tipo, 'equipo': equipo_codigo, 'espacio': espacio, 'duracion': duracion,
             'espera': espera, 'personas': personas, 'rendimiento': rendimiento, 'distancia': distancia,
             'instrucciones': instrucciones}
    control = pcc or pc
    if control:
        datos.update({'punto_critico': bool(pcc), 'punto_control': bool(pc),
                      'parametro': control[0], 'limite': control[1]})
    return datos


def receta(codigo, nombre, producto_codigo, cantidad_base, unidad_base, rendimiento, horas, instrucciones,
           etapas, insumos, salidas=(), software=()):
    return {
        'codigo': codigo, 'nombre': nombre, 'producto': producto_codigo, 'cantidad_base': cantidad_base,
        'unidad_base': unidad_base, 'rendimiento_esperado': rendimiento, 'duracion_horas': horas,
        'instrucciones': instrucciones, 'etapas': etapas, 'insumos': list(insumos), 'salidas': list(salidas),
        'software': list(software),
    }


